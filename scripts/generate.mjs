import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { transform } from "@svgr/core";
import jsx from "@svgr/plugin-jsx";
import { check } from "./check.mjs";
import { componentNameFor, optimizeSvg, readSets, root } from "./lib.mjs";

const HEADER = "// Generated by scripts/generate.mjs from svg/. Don't edit; change the SVG in Figma and re-export.\n";

/** Icons take a `size` prop, like @untitledui/icons. Flags and logos keep their Figma dimensions. */
const sizedTemplate = (variables, { tpl }) => tpl`
import { a11y } from "../a11y";
import type { IconProps } from "../types";

const ${variables.componentName} = ({ size = DEFAULT_SIZE, ...props }: IconProps) => ${variables.jsx};

${variables.exports};
`;

const plainTemplate = (variables, { tpl }) => tpl`
import type { SVGProps } from "react";
import { a11y } from "../a11y";

const ${variables.componentName} = (props: SVGProps<SVGSVGElement>) => ${variables.jsx};

${variables.exports};
`;

const toComponent = async (svg, { config, component }) => {
    const code = await transform(
        svg,
        {
            plugins: [jsx],
            typescript: true,
            jsxRuntime: "automatic",
            expandProps: "end",
            template: config.size ? sizedTemplate : plainTemplate,
            svgProps: config.size ? { width: "{size}", height: "{size}" } : undefined,
        },
        { componentName: component },
    );
    // Icons are hidden by default; flags and logos stay as they were. A label makes any of them an image.
    const spread = config.size ? "{...a11y(props, true)} {...props}" : "{...a11y(props)} {...props}";

    return (
        HEADER +
        code
            .replace("DEFAULT_SIZE", String(config.size))
            .replace("{...props}", spread)
            .replace(/^export default/m, `${component}.displayName = "${component}";\n\nexport default`)
    );
};

const A11Y = `${HEADER}import type { SVGProps } from "react";

/**
 * Screen reader attributes, spread before the caller's props so an explicit \`aria-hidden\` or \`role\` still wins.
 * With \`aria-label\` or \`aria-labelledby\` the SVG is an image (\`role="img"\`, not hidden); without one it's
 * \`aria-hidden\` when \`hidden\` is set.
 */
export const a11y = (props: SVGProps<SVGSVGElement>, hidden = false): SVGProps<SVGSVGElement> =>
    props["aria-label"] != null || props["aria-labelledby"] != null ? { role: "img" } : hidden ? { "aria-hidden": true } : {};
`;

const TYPES = `${HEADER}import type { SVGProps } from "react";

export interface IconProps extends SVGProps<SVGSVGElement> {
    /** Width and height. Defaults to the Figma frame (20). A Tailwind \`size-*\` class overrides it. */
    size?: number | string;
}
`;

/** \`<Flag name="norway-nok" />\`: the same API the design system had in components/foundations/flags. */
const flagLookup = (files) => `${HEADER}import type { SVGProps } from "react";
import { a11y } from "../a11y";
${files.map(({ name, component }) => `import ${component} from "./${name}";`).join("\n")}

/** Flags by Figma name: \`<country>-<currency>\`, plus \`globe\`. */
export const flags = {
${files.map(({ name, component }) => `    ${/^[a-z]+$/.test(name) ? name : JSON.stringify(name)}: ${component},`).join("\n")}
};

export type FlagName = keyof typeof flags;

export interface FlagProps extends SVGProps<SVGSVGElement> {
    /** Figma flag name, e.g. \`"argentina-ars"\`: country, then its ISO 4217 currency code. */
    name: FlagName;
}

/** A round flag. Decorative by default; give it an \`aria-label\` when it carries meaning on its own. */
export const Flag = ({ name, ...props }: FlagProps) => {
    const Component = flags[name];

    return <Component {...a11y(props, true)} {...props} />;
};
`;

/** Turns svg/ into one .tsx per asset in `outDir`, plus the indexes tsup builds from and the cleaned SVGs in `outDir/public/svg`. */
export const generate = async (svgDir = join(root, "svg"), outDir = join(root, "src")) => {
    const problems = check(svgDir);
    if (problems.length) throw new Error(`Fix these SVGs first (npm run check):\n${problems.map((problem) => `  - ${problem}`).join("\n")}`);

    rmSync(outDir, { recursive: true, force: true });
    mkdirSync(outDir, { recursive: true });
    writeFileSync(join(outDir, "types.ts"), TYPES);
    writeFileSync(join(outDir, "a11y.ts"), A11Y);

    const exports = ['export type { IconProps } from "./types";'];

    for (const { set, config, files } of readSets(svgDir)) {
        mkdirSync(join(outDir, set), { recursive: true });
        const svgOut = join(outDir, "public/svg", set);
        mkdirSync(svgOut, { recursive: true });

        const generated = await Promise.all(
            files.map(async ({ name, source }) => {
                const component = componentNameFor(config, name);
                const svg = optimizeSvg(source, { set, config, name });
                // The cleaned SVG (currentColor, unique ids) is what apps get in fa-icons/svg/*, e.g. for a sprite.
                writeFileSync(join(svgOut, `${name}.svg`), svg);
                writeFileSync(join(outDir, set, `${name}.tsx`), await toComponent(svg, { config, component }));

                return { name, component };
            }),
        );

        exports.push(...generated.map(({ name, component }) => `export { default as ${component} } from "./${set}/${name}";`));

        if (set === "flags" && generated.length) {
            writeFileSync(join(outDir, set, "flag.tsx"), flagLookup(generated));
            exports.push('export { Flag, flags } from "./flags/flag";', 'export type { FlagName, FlagProps } from "./flags/flag";');
        }
    }

    writeFileSync(join(outDir, "index.ts"), `${HEADER}${exports.join("\n")}\n`);

    return readSets(svgDir).map(({ set, files }) => `${files.length} ${set}`);
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    try {
        console.log(`Generated ${(await generate(process.argv[2], process.argv[3])).join(", ")}.`);
    } catch (error) {
        console.error(error.message);
        process.exit(1);
    }
}
